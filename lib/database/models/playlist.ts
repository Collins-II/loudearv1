// models/playlist.ts

import { Schema, model, models, Types } from "mongoose";

export interface IPlaylist {
  title: string;
  description?: string;
  image?: string;

  mood?: string;
  genre?: string;

  curator?: string;

  songs: Types.ObjectId[];

  autoGenerated: boolean;

  visibility: "public" | "private";

  createdAt: Date;
  updatedAt: Date;
}

const PlaylistSchema = new Schema<IPlaylist>(
  {
    title: { type: String, required: true },

    description: String,

    image: String,

    mood: String,

    genre: String,

    curator: {
      type: String,
      default: "LoudEar",
    },

    songs: [
      {
        type: Schema.Types.ObjectId,
        ref: "Song",
      },
    ],

    autoGenerated: {
      type: Boolean,
      default: false,
    },

    visibility: {
      type: String,
      enum: ["public", "private"],
      default: "public",
    },
  },
  {
    timestamps: true,
  }
);

export const Playlist = models?.Playlist || model<IPlaylist>("Playlist", PlaylistSchema);