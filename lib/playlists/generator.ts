export async function generateForUser(
  userId: string
) {
  const history = await ListeningHistory.find({
    user: userId,
  }).populate("song");

  const genres = history.map(
    (h: any) => h.song.genre
  );

  const favoriteGenre = mostCommon(genres);

  const songs = await Song.find({
    genre: favoriteGenre,
    visibility: "public",
  })
    .limit(100);

  return {
    title: "Made For You",
    songs,
  };
}

export async function generateTrendingPlaylist() {
  const songs = await Song.find({
    visibility: "public",
  });

  songs.sort((a, b) => {
    const scoreA =
      a.views.length +
      a.likes.length * 3 +
      a.shares.length * 5;

    const scoreB =
      b.views.length +
      b.likes.length * 3 +
      b.shares.length * 5;

    return scoreB - scoreA;
  });

  return upsertPlaylist(
    "Trending Now",
    {
      title: "Trending Now",
      songs: songs.slice(0, 100),
      autoGenerated: true,
    }
  );
}

