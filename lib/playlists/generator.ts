export async function generateViralTracks() {
  const last7Days = new Date();
  last7Days.setDate(
    last7Days.getDate() - 7
  );

  const songs = await Song.find({
    createdAt: {
      $gte: last7Days,
    },
    visibility: "public",
  });

  songs.sort((a, b) => {
    const scoreA =
      a.views.length +
      a.likes.length +
      a.shares.length;

    const scoreB =
      b.views.length +
      b.likes.length +
      b.shares.length;

    return scoreB - scoreA;
  });

  return upsertPlaylist(
    "Viral Tracks",
    {
      title: "Viral Tracks",
      songs: songs.slice(0, 100),
      autoGenerated: true,
    }
  );
}

export async function generateRisingArtists() {
  const songs = await Song.find({
    visibility: "public",
  });

  const newArtists = songs.filter(
    (s) =>
      s.views.length > 500 &&
      s.views.length < 5000
  );

  return upsertPlaylist(
    "Rising Artists",
    {
      title: "Rising Artists",
      songs: newArtists.slice(0, 100),
      autoGenerated: true,
    }
  );
}

