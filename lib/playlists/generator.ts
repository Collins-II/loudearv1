export async function regenerateAutoPlaylists() {
    const moods = [
    "Happy",
    "Sad",
    "Chill",
    "Workout",
    "Focus",
    "Romantic",
  ];

  for (const mood of moods) {
    await generateMoodPlaylist(mood);
  }

  const playlists = await Promise.all([
  generateTrendingPlaylist(),
  generateNewReleases(),
  generateMostStreamed(),
  generateMostDownloaded(),
  generateEditorsPicks(),
  generateZambiaTop100(),
  generateAfricaTop100(),
  generateGenrePlaylist("Gospel"),
  generateGenrePlaylist("Hip Hop"),
  generateGenrePlaylist("Afro Pop"),
  generateMoodPlaylist("Workout"),
  generateMoodPlaylist("Chill"),
  generateMoodPlaylist("Focus"),
  generateMoodPlaylist("Romantic"),
  generateViralTracks(),
  generateRisingArtists(),
  generateOriginals(),
]);

return playlists.filter(Boolean);
}