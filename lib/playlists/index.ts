import { Playlist } from "@/lib/database/models/playlist";

interface FetchOptions {
  mood?: string;
  region?: string;
  sort?: string;
  limit?: number;
}

export async function fetchPlaylists({
  mood,
  region,
  sort = "relevance",
  limit = 30,
}: FetchOptions = {}) {
  const query: any = {
    autoGenerated: true,
  };

  if (mood && mood !== "All") {
    query.$or = [
      { mood: mood },
      { title: { $regex: mood, $options: "i" } },
      { description: { $regex: mood, $options: "i" } },
    ];
  }

  if (region && region !== "global") {
    query.region = region;
  }

  let sortQuery: any = {
    updatedAt: -1,
  };

  switch (sort) {
    case "followers":
      sortQuery = { followersCount: -1 };
      break;

    case "tracks":
      sortQuery = { trackCount: -1 };
      break;

    case "relevance":
    default:
      sortQuery = {
        featured: -1,
        updatedAt: -1,
      };
  }

  const playlistsObject = await Playlist.find({
  autoGenerated: true,
});

console.log("DATA_OBJECT", playlistsObject);

const count = await Playlist.countDocuments();

const all = await Playlist.find({}).lean();

const auto = await Playlist.find({
  autoGenerated: true,
}).lean();

console.log("COUNT:", count);
console.log("ALL:", all);
console.log("AUTO:", auto);

  const playlists = await Playlist.find(query)
    .populate("songs")
    .sort(sortQuery)
    .limit(limit)
    .lean();

  return playlists.map((playlist: any) => ({
    id: playlist._id.toString(),
    title: playlist.title,
    curator: playlist.autoGenerated
      ? "LoudEar"
      : playlist.curator || "Unknown",

    image:
      playlist.image ||
      "/images/default-playlist.jpg",

    tracks:
      playlist.songs?.length || 0,

    plays:
      playlist.plays || 0,

    lastWeek:
      playlist.lastWeek || 0,
  }));
}

export async function fetchPlaylistById(
  id: string
) {
  return Playlist.findById(id)
    .populate({
      path: "songs",
      populate: {
        path: "author",
      },
    })
    .lean();
}